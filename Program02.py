# โปรแกรมคำนวณพื้นที่รูปทรงเรขาคณิตอัจฉริยะ (เวอร์ชันพัฒนาต่อยอด)

print("=== โปรแกรมคำนวณพื้นที่เรขาคณิต ===")
print("1. รูปสี่เหลี่ยมมุมฉาก")
print("2. รูปสามเหลี่ยม")
print("3. รูปวงกลม")
# รับค่าตัวเลือกจากผู้ใช้งาน
ตัวเลือก = input("กรุณาเลือกรูปทรงที่ต้องการคำนวณ (1/2/3): ")

# กรณีเลือก 1: คำนวณพื้นที่รูปสี่เหลี่ยมมุมฉาก (พัฒนาจากโค้ดต้นแบบให้รับค่าได้ยืดหยุ่น)
if ตัวเลือก == "1":
    กว้าง = float(input("ป้อนความกว้าง (เซนติเมตร): "))
    ยาว = float(input("ป้อนความยาว (เซนติเมตร): "))
    
    if กว้าง > 0 and ยาว > 0:
        พื้นที่ = กว้าง * ยาว
        print("-> พื้นที่รูปสี่เหลี่ยมมุมฉากคือ:", พื้นที่, "ตารางเซนติเมตร")
    else:
        print("❌ ข้อผิดพลาด: ค่าความกว้างและความยาวต้องมากกว่า 0")

# กรณีเลือก 2: เพิ่มฟังก์ชันคำนวณพื้นที่รูปสามเหลี่ยม
elif ตัวเลือก == "2":
    ฐาน = float(input("ป้อนความยาวฐาน (เซนติเมตร): "))
    สูง = float(input("ป้อนความสูง (เซนติเมตร): "))
    
    if ฐาน > 0 and สูง > 0:
        พื้นที่ = 0.5 * ฐาน * สูง
        print("-> พื้นที่รูปสามเหลี่ยมคือ:", พื้นที่, "ตารางเซนติเมตร")
    else:
        print("❌ ข้อผิดพลาด: ค่าฐานและค่าความสูงต้องมากกว่า 0")

# กรณีเลือก 3: เพิ่มฟังก์ชันคำนวณพื้นที่รูปวงกลม
elif ตัวเลือก == "3":
    รัศมี = float(input("ป้อนความยาวรัศมีวงกลม (เซนติเมตร): "))
    
    if รัศมี > 0:
        # ใช้ค่า พาย (Pi) ประมาณ 3.14
        พื้นที่ = 3.14 * (รัศมี ** 2)
        print("-> พื้นที่รูปวงกลมคือ:", พื้นที่, "ตารางเซนติเมตร")
    else:
        print("❌ ข้อผิดพลาด: ค่ารัศมีต้องมากกว่า 0")

else:
    print("❌ คุณเลือกเมนูไม่ถูกต้อง กรุณารันโปรแกรมใหม่อีกครั้ง")